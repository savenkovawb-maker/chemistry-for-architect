-- Supabase setup for "Химия для будущего архитектора"
-- Run once in Supabase SQL Editor.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null check (role in ('student','parent')),
  created_at timestamptz not null default now()
);

create table if not exists public.lesson_progress (
  student_id uuid not null references auth.users(id) on delete cascade,
  lesson_id integer not null check (lesson_id between 1 and 48),
  started_at timestamptz,
  completed_at timestamptz,
  video_opened_at timestamptz,
  quiz_correct integer check (quiz_correct is null or quiz_correct >= 0),
  quiz_total integer check (quiz_total is null or quiz_total >= 0),
  last_activity timestamptz not null default now(),
  primary key (student_id, lesson_id)
);

create table if not exists public.parent_student (
  parent_id uuid not null references auth.users(id) on delete cascade,
  student_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(parent_id, student_id),
  constraint no_self_link check (parent_id <> student_id)
);

create table if not exists public.parent_invites (
  id bigint generated by default as identity primary key,
  student_id uuid not null references auth.users(id) on delete cascade,
  code text not null unique,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists lesson_progress_student_idx on public.lesson_progress(student_id);
create index if not exists parent_student_parent_idx on public.parent_student(parent_id);
create index if not exists parent_student_student_idx on public.parent_student(student_id);
create index if not exists parent_invites_student_idx on public.parent_invites(student_id);

alter table public.profiles enable row level security;
alter table public.lesson_progress enable row level security;
alter table public.parent_student enable row level security;
alter table public.parent_invites enable row level security;

revoke all on table public.profiles, public.lesson_progress, public.parent_student, public.parent_invites from anon, authenticated;
grant select, insert on table public.profiles to authenticated;
grant select, insert, update, delete on table public.lesson_progress to authenticated;
grant select on table public.parent_student to authenticated;

-- profiles: own profile + parent can see linked student's display name
create policy "profiles_select" on public.profiles for select to authenticated
using (
  (select auth.uid()) = id
  or exists (
    select 1 from public.parent_student ps
    where ps.parent_id = (select auth.uid()) and ps.student_id = public.profiles.id
  )
);
create policy "profiles_insert_own" on public.profiles for insert to authenticated
with check ((select auth.uid()) = id);
-- progress: student writes own rows; linked parent can only read
create policy "progress_select" on public.lesson_progress for select to authenticated
using (
  student_id = (select auth.uid())
  or exists (
    select 1 from public.parent_student ps
    where ps.parent_id = (select auth.uid()) and ps.student_id = public.lesson_progress.student_id
  )
);
create policy "progress_insert_own" on public.lesson_progress for insert to authenticated
with check (student_id = (select auth.uid()));
create policy "progress_update_own" on public.lesson_progress for update to authenticated
using (student_id = (select auth.uid())) with check (student_id = (select auth.uid()));
create policy "progress_delete_own" on public.lesson_progress for delete to authenticated
using (student_id = (select auth.uid()));

-- relation itself: either side may see its own link; writes only through RPC functions
create policy "links_select_own" on public.parent_student for select to authenticated
using (parent_id = (select auth.uid()) or student_id = (select auth.uid()));

-- Invite table has NO direct grants/policies for browser users.

create or replace function public.create_parent_invite()
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_code text;
begin
  if v_uid is null then raise exception 'Not authenticated'; end if;
  if not exists (select 1 from public.profiles where id=v_uid and role='student') then
    raise exception 'Only a student account can create an invite';
  end if;
  update public.parent_invites set used_at=pg_catalog.now()
    where student_id=v_uid and used_at is null;
  v_code := pg_catalog.upper(pg_catalog.substr(pg_catalog.md5(pg_catalog.random()::text || pg_catalog.clock_timestamp()::text),1,8));
  insert into public.parent_invites(student_id,code,expires_at)
    values(v_uid,v_code,pg_catalog.now()+interval '7 days');
  return v_code;
end;
$$;

create or replace function public.accept_parent_invite(p_code text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_student uuid;
begin
  if v_uid is null then raise exception 'Not authenticated'; end if;
  if not exists (select 1 from public.profiles where id=v_uid and role='parent') then
    raise exception 'Only a parent account can accept an invite';
  end if;
  select student_id into v_student
    from public.parent_invites
    where code=pg_catalog.upper(pg_catalog.trim(p_code))
      and used_at is null and expires_at > pg_catalog.now()
    order by id desc limit 1 for update;
  if v_student is null then raise exception 'Invite code is invalid or expired'; end if;
  if v_student=v_uid then raise exception 'Cannot link account to itself'; end if;
  insert into public.parent_student(parent_id,student_id)
    values(v_uid,v_student) on conflict do nothing;
  update public.parent_invites set used_at=pg_catalog.now()
    where student_id=v_student and code=pg_catalog.upper(pg_catalog.trim(p_code)) and used_at is null;
  return v_student;
end;
$$;

revoke execute on function public.create_parent_invite() from public, anon;
revoke execute on function public.accept_parent_invite(text) from public, anon;
grant execute on function public.create_parent_invite() to authenticated;
grant execute on function public.accept_parent_invite(text) to authenticated;
